/**
 * packs.js — the rule packs.
 *
 * Design rules for this file (they are part of the product's honesty claim):
 *
 *  1. No long verbatim quotations of any copyrighted or official text. Every
 *     clause is a short, hand-written paraphrase: rule name + clause number +
 *     one line of what it requires. `basis.note` says where the paraphrase comes
 *     from and that it is a paraphrase.
 *  2. Every clause declares *when it applies* (`applies`) and *what counts as
 *     satisfying it* (`satisfied`). The engine does not invent either.
 *  3. `suggestedText` is ready-to-paste wording the user can drop into the
 *     deliverable. It is a draft, not legal advice — said in the UI as well.
 *
 * Clause shape
 *   ref            clause number inside the pack, used in the gap list
 *   title          short human label
 *   requirement    one line: what the rule asks for
 *   severity       high | medium | low
 *   advisory       true -> reported as guidance, never counted as a gap
 *   applies        predicate over signals (see engine.js testPredicate)
 *   satisfied      { mode: "any" | "all", groups: [{ label, phrases: [...] }] }
 *   exemptIf       predicate; when true the clause is reported as exempt, with `exemptReason`
 *   remediation    what to do about the gap
 *   suggestedText  wording to insert into the deliverable
 *   insertInto     where in a document the wording usually belongs
 */

