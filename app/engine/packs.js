export const PACKS = [euAiAct, tenderAiDisclosure, platformLabelling, competitionDeclaration];

export const PACK_INDEX = Object.fromEntries(PACKS.map((p) => [p.id, p]));

/** Total clause count across all packs — used by the UI and by tests. */
export const TOTAL_CLAUSES = PACKS.reduce((n, p) => n + p.clauses.length, 0);

export function getPack(id) {
  const pack = PACK_INDEX[id];
  if (!pack) throw new Error("unknown rule pack: " + id);
  return pack;
}

export function clauseById(packId, ref) {
  const pack = getPack(packId);
  const clause = pack.clauses.find((c) => c.ref === ref);
  if (!clause) throw new Error("unknown clause: " + packId + " " + ref);
  return clause;
}
